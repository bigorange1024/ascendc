/**
 * @file cbd3_ab_lut.h
 * @brief Alg.8 η=3 系数 LUT — (a,b) ↦ (a−b) mod 3329。
 *
 * 背景：ML-KEM-512 的 s 采样使用 η1=3；每个系数由 6 个比特组成，
 * 低 3 个比特求和得到 a，高 3 个比特求和得到 b，输出为 (a-b) mod q。
 * 本表把 a,b∈[0,7] 的 64 种结果预先展开，设备 hot path 只做 SWAR 位抽取
 * 与查表，避免每个系数上的条件分支和运行时取模。
 */
#pragma once

#include <cstdint>

namespace F203CbdEta3 {

/**
 * 64 项 ROM：行主序 a=0..7，列 b=0..7，索引 `(a<<3)|b`。
 * 数值与 `golden_se_sampling.sample_poly_cbd3` / C `fips203_sample_poly_cbd3_row`
 * 一致：负差加 q=3329 后落在 [0,q)。
 */
constexpr int32_t CBD3_AB_LUT[64] = {
    0, 3328, 3327, 3326, 3325, 3324, 3323, 3322,  // a=0
    1, 0,    3328, 3327, 3326, 3325, 3324, 3323,  // a=1
    2, 1,    0,    3328, 3327, 3326, 3325, 3324,  // a=2
    3, 2,    1,    0,    3328, 3327, 3326, 3325,  // a=3
    4, 3,    2,    1,    0,    3328, 3327, 3326,  // a=4
    5, 4,    3,    2,    1,    0,    3328, 3327,  // a=5
    6, 5,    4,    3,    2,    1,    0,    3328,  // a=6
    7, 6,    5,    4,    3,    2,    1,    0,     // a=7
};

}  // namespace F203CbdEta3
